
public class SwappingOfTwoNumber {
    public static void main(String[] args) {
        int a = 10;
        int b = 20;
        System.out.println("a = "+ a+ " b = " + b);

        System.out.println("After Swapping of Two number ");
        int temp = a;
        a = b;
        b = temp;
        System.out.println("a = "+ a+ " b = " + b);
    }
}


// a = 10 b = 20
// After Swapping of Two number 
// a = 20 b = 10