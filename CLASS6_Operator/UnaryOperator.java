
public class UnaryOperator {
    public static void main(String args[]){
        int a = 20;
        System.out.println(a++); // 20
        System.out.println(++a); // 22
        System.out.println(a++); // 22
        System.out.println(++a); // 24
        System.out.println(--a); // 23
        System.out.println(a--); // 23
        System.out.println(-a); // -22
    }    
}

